"use client";

import type { ReactNode } from "react";
import { whatsappLink } from "@/config/site";

type Props = {
  message: string;
  // Identifica o CTA para mensuração futura (ex.: GTM via window.dataLayer).
  cta: string;
  className?: string;
  children: ReactNode;
};

declare global {
  interface Window {
    dataLayer?: Record<string, unknown>[];
  }
}

export function WhatsAppLink({ message, cta, className, children }: Props) {
  return (
    <a
      href={whatsappLink(message)}
      target="_blank"
      rel="noopener noreferrer"
      data-cta={cta}
      className={className}
      onClick={() => window.dataLayer?.push({ event: "whatsapp_click", cta })}
    >
      {children}
    </a>
  );
}

